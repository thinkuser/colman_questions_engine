/**
 * V4 gender-inclusive presentation copy (DEC-036). V4 reuses the shared V3 screens and the shared question / world /
 * project / result content, whose approved V2/V3 wording addresses the candidate in the masculine plural ("אתם",
 * "לכם", "בחרו"). V4 must read gender-inclusively WITHOUT changing V2/V3, so this module is a thin presentation layer:
 *
 *  - `V4_UI_COPY`: the V3 screen copy (same shape as `V3_COPY`) with V4 wording;
 *  - `V4_LEAD_COPY`: the lead form copy (same shape as `V2_LEAD_COPY`); the legal consent text is unchanged;
 *  - `V4_TEXT_OVERRIDES` / `v4Text`: exact-string rewrites of shared content (question prompts and options, program
 *    meaning, pair guidance, V1 Tech evidence lines...). Keyed by the ORIGINAL string, so ids, mappings, weights,
 *    routing and the content files themselves are untouched; a string without an override renders as is.
 *
 * Style: prefer impersonal phrasing ("אפשר לבחור", "ממשיכים", "להכיר את...") and forms spelled the same for every
 * gender (לך, אותך, שלך, אליך, דעתך; past "בחרת", "עצרת"; "היית רוצה"). Paired forms (״מאשר/ת״) only where neither
 * reads naturally. Tests keep every key tied to live content and scan the whole V4 surface (tests/data/v4InclusiveCopy).
 */

/** The structural shape of a copy object, with literal strings widened so another version can supply its wording. */
export type CopyShape<T> = T extends string
  ? string
  : T extends (...args: infer A) => string
    ? (...args: A) => string
    : T extends readonly (infer U)[]
      ? readonly CopyShape<U>[]
      : { readonly [K in keyof T]: CopyShape<T[K]> };

